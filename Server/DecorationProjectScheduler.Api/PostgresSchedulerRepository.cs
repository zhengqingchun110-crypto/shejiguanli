            SELECT id, project_code, name, status, manager_id, area, project_type, operator_names, task_plan, start_date, end_date, summary, updated_at, archived
            FROM projects
            ORDER BY updated_at DESC;
            """, connection);
        await using var reader = await command.ExecuteReaderAsync();
        var list = new List<Project>();
        while (await reader.ReadAsync())
        {
            list.Add(new Project
            {
                Id = reader.GetInt32(0),
                ProjectCode = reader.GetString(1),
                Name = reader.GetString(2),
                Status = reader.GetString(3),
                ManagerId = reader.GetInt32(4),
                Area = reader.GetString(5),
                ProjectType = reader.GetString(6),
                OperatorNames = reader.GetString(7),
                TaskPlan = reader.GetString(8),
                StartDate = reader.GetDateTime(9),
                EndDate = reader.GetDateTime(10),
                Summary = reader.GetString(11),
                UpdatedAt = reader.GetDateTime(12),
                Archived = reader.GetBoolean(13)
            });
        }

        return list;
    }

