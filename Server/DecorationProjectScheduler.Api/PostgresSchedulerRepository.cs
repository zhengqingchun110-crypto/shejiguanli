            INSERT INTO employees (name, role, department)
            VALUES (@name, @role, @department);
            """,
            ("name", request.Name),
            ("role", request.Role),
            ("department", request.Department));
    }

    public async Task DeleteEmployeeAsync(int employeeId)
    {
        await ExecuteAsync("""
            DELETE FROM tasks WHERE owner_id = @employeeId;
            DELETE FROM employees WHERE id = @employeeId;
            """,
            ("employeeId", employeeId));
    }

    public async Task CreateProjectAsync(CreateProjectRequest request)
    {
        await using var connection = new NpgsqlConnection(_connectionString);
        await connection.OpenAsync();
        await using var transaction = await connection.BeginTransactionAsync();

        var code = $"{DateTime.Today:yyyy}{await ScalarAsync<long>(connection, "SELECT COUNT(*) + 1 FROM projects;", transaction):000}";
        var projectId = await ScalarAsync<int>(connection, """
            INSERT INTO projects (project_code, name, status, manager_id, area, project_type, operator_names, task_plan, start_date, end_date, summary, updated_at, archived)
            VALUES (@code, @name, '规划中', @managerId, @area, @projectType, '', '', @startDate, @endDate, @summary, @updatedAt, FALSE)
            RETURNING id;
            """,
            transaction,
            ("code", code),
            ("name", request.Name),
            ("managerId", request.ManagerId),
            ("area", request.Area),
            ("projectType", request.ProjectType),
            ("startDate", request.StartDate.Date),
            ("endDate", request.EndDate.Date),
            ("summary", request.Summary),
            ("updatedAt", DateTime.Now));

        var totalDays = Math.Max((request.EndDate.Date - request.StartDate.Date).Days, DesignStageTemplates.DefaultStages.Length);
        for (var i = 0; i < DesignStageTemplates.DefaultStages.Length; i++)
        {
            await ExecuteAsync(connection, """
                INSERT INTO project_stages (project_id, stage_name, sequence_no, planned_date, completed_date, status)
                VALUES (@projectId, @stageName, @sequenceNo, @plannedDate, NULL, '待执行');
                """,
                transaction,
                ("projectId", projectId),
                ("stageName", DesignStageTemplates.DefaultStages[i]),
                ("sequenceNo", i + 1),
                ("plannedDate", request.StartDate.Date.AddDays(i * totalDays / DesignStageTemplates.DefaultStages.Length)));
        }

        await transaction.CommitAsync();
    }

    public async Task UpdateProjectAsync(int projectId, UpdateProjectRequest request)
    {
        await ExecuteAsync("""
            UPDATE projects
            SET name = @name,
                area = @area,
                project_type = @projectType,
                operator_names = @operatorNames,
                summary = @summary,
                task_plan = @taskPlan,
                updated_at = @updatedAt
            WHERE id = @projectId;
            """,
            ("projectId", projectId),
            ("name", request.Name),
            ("area", request.Area),
            ("projectType", request.ProjectType),
            ("operatorNames", request.OperatorNames),
            ("summary", request.Summary),
            ("taskPlan", request.TaskPlan),
            ("updatedAt", DateTime.Now));
    }

    public async Task DeleteProjectAsync(int projectId) =>
        await ExecuteAsync("DELETE FROM projects WHERE id = @projectId;", ("projectId", projectId));

    public async Task AddTaskAsync(AddTaskRequest request)
    {
        await ExecuteAsync("""
            INSERT INTO tasks (project_id, name, owner_id, workload_percent, progress_percent, start_date, end_date, status)
            VALUES (@projectId, @name, @ownerId, @workload, @progress, @startDate, @endDate, @status);
            """,
            ("projectId", request.ProjectId),
            ("name", request.Name),
            ("ownerId", request.OwnerId),
            ("workload", request.WorkloadPercent),
            ("progress", request.ProgressPercent),
            ("startDate", request.StartDate.Date),
            ("endDate", request.EndDate.Date),
            ("status", request.Status));
        await TouchProjectAsync(request.ProjectId);
    }

    public async Task UpdateTaskAsync(int taskId, UpdateTaskRequest request)
    {
        var projectId = await GetTaskProjectIdAsync(taskId);
        await ExecuteAsync("UPDATE tasks SET name = @name WHERE id = @taskId;", ("taskId", taskId), ("name", request.Name));
        await TouchProjectAsync(projectId);
    }

    public async Task UpdateTaskScheduleAsync(int taskId, UpdateTaskScheduleRequest request)
    {
        var previousProjectId = await GetTaskProjectIdAsync(taskId);
        await ExecuteAsync("""
            UPDATE tasks
            SET project_id = @projectId,
                name = @name,
                end_date = @endDate,
                status = CASE WHEN progress_percent >= 100 THEN '已完成' ELSE status END
            WHERE id = @taskId;
            """,
            ("taskId", taskId),
            ("projectId", request.ProjectId),
            ("name", request.Name),
            ("endDate", request.EndDate.Date));
        await TouchProjectAsync(previousProjectId);
        await TouchProjectAsync(request.ProjectId);
    }

    public async Task DeleteTaskAsync(int taskId)
    {
        var projectId = await GetTaskProjectIdAsync(taskId);
        await ExecuteAsync("DELETE FROM tasks WHERE id = @taskId;", ("taskId", taskId));
        await TouchProjectAsync(projectId);
    }

    public async Task CompleteTaskWithFollowUpAsync(int taskId)
    {
        await using var connection = new NpgsqlConnection(_connectionString);
        await connection.OpenAsync();
        await using var transaction = await connection.BeginTransactionAsync();

        await using var query = CreateCommand(connection, """
            SELECT tasks.project_id, tasks.name, COALESCE(employees.name, '')
            FROM tasks
            LEFT JOIN employees ON employees.id = tasks.owner_id
            WHERE tasks.id = @taskId;
            """,
            transaction,
            ("taskId", taskId));
        await using var reader = await query.ExecuteReaderAsync();
        if (!await reader.ReadAsync())
        {
            return;
        }

        var projectId = reader.GetInt32(0);
        var taskName = reader.GetString(1);
        var operatorName = reader.GetString(2);
        await reader.DisposeAsync();

        await ExecuteAsync(connection, "UPDATE tasks SET progress_percent = 100, status = '已完成' WHERE id = @taskId;", transaction, ("taskId", taskId));
        await ExecuteAsync(connection, """
            INSERT INTO project_follow_ups (project_id, task_id, content, operator_name, completed_at)
            VALUES (@projectId, @taskId, @content, @operatorName, @completedAt);
            """,
            transaction,
            ("projectId", projectId),
            ("taskId", taskId),
            ("content", taskName),
            ("operatorName", operatorName),
            ("completedAt", DateTime.Now));
        await TouchProjectAsync(connection, transaction, projectId);
        await transaction.CommitAsync();
    }

