using DecorationProjectScheduler.App.Helpers;
using DecorationProjectScheduler.App.Models;
using Npgsql;

namespace DecorationProjectScheduler.Api;

public sealed class PostgresSchedulerRepository
{
    private readonly string _connectionString;

    public PostgresSchedulerRepository(IConfiguration configuration)
    {
        _connectionString = configuration.GetConnectionString("Scheduler")
            ?? Environment.GetEnvironmentVariable("SCHEDULER_CONNECTION_STRING")
            ?? throw new InvalidOperationException("缺少数据库连接字符串 Scheduler。");
    }

    public async Task InitializeAsync()
    {
        await using var connection = new NpgsqlConnection(_connectionString);
        await connection.OpenAsync();

        await ExecuteAsync(connection, """
            CREATE TABLE IF NOT EXISTS employees (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                role TEXT NOT NULL DEFAULT '',
                department TEXT NOT NULL DEFAULT ''
            );

            CREATE TABLE IF NOT EXISTS projects (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                project_code TEXT NOT NULL UNIQUE,
                name TEXT NOT NULL,
                status TEXT NOT NULL,
                manager_id INTEGER NOT NULL,
                area TEXT NOT NULL DEFAULT '',
                project_type TEXT NOT NULL DEFAULT '',
                operator_names TEXT NOT NULL DEFAULT '',
                task_plan TEXT NOT NULL DEFAULT '',
                start_date DATE NOT NULL,
                end_date DATE NOT NULL,
                summary TEXT NOT NULL DEFAULT '',
                updated_at TIMESTAMP NOT NULL,
                archived BOOLEAN NOT NULL DEFAULT FALSE
            );

            CREATE TABLE IF NOT EXISTS project_stages (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
                stage_name TEXT NOT NULL,
                sequence_no INTEGER NOT NULL,
                planned_date DATE NOT NULL,
                completed_date DATE NULL,
                status TEXT NOT NULL
            );

            CREATE TABLE IF NOT EXISTS tasks (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
                name TEXT NOT NULL,
                owner_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
                workload_percent INTEGER NOT NULL,
                progress_percent INTEGER NOT NULL,
                start_date DATE NOT NULL,
                end_date DATE NOT NULL,
                status TEXT NOT NULL
            );

            CREATE TABLE IF NOT EXISTS site_visits (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
                visit_date DATE NOT NULL,
                issues TEXT NOT NULL,
                suggestions TEXT NOT NULL,
                photo_path TEXT NOT NULL DEFAULT '',
                rectification_status TEXT NOT NULL
            );

            CREATE TABLE IF NOT EXISTS handover_records (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
                handover_date DATE NOT NULL,
                participants TEXT NOT NULL,
                attachment_path TEXT NOT NULL DEFAULT '',
                notes TEXT NOT NULL DEFAULT ''
            );

            CREATE TABLE IF NOT EXISTS acceptance_records (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
                acceptance_date DATE NOT NULL,
                result TEXT NOT NULL,
                rectification_items TEXT NOT NULL,
                review_record TEXT NOT NULL,
                status TEXT NOT NULL
            );

            CREATE TABLE IF NOT EXISTS project_files (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
                category TEXT NOT NULL,
                file_name TEXT NOT NULL,
                file_path TEXT NOT NULL,
                uploaded_at TIMESTAMP NOT NULL
            );

            CREATE TABLE IF NOT EXISTS project_follow_ups (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
                task_id INTEGER NULL,
                content TEXT NOT NULL,
                operator_name TEXT NOT NULL,
                completed_at TIMESTAMP NOT NULL
            );
            """);
        // 正式版只初始化表结构，不自动写入演示员工，避免更新或迁移时污染公司人员数据。
    }

    public async Task<WorkspaceSnapshot> GetSnapshotAsync()
    {
        await using var connection = new NpgsqlConnection(_connectionString);
        await connection.OpenAsync();

        return new WorkspaceSnapshot
        {
            Employees = await ReadEmployeesAsync(connection),
            Projects = await ReadProjectsAsync(connection),
            ProjectStages = await ReadStagesAsync(connection),
            Tasks = await ReadTasksAsync(connection),
            SiteVisits = await ReadSiteVisitsAsync(connection),
            HandoverRecords = await ReadHandoversAsync(connection),
            AcceptanceRecords = await ReadAcceptancesAsync(connection),
            ProjectFiles = await ReadFilesAsync(connection),
            ProjectFollowUps = await ReadFollowUpsAsync(connection)
        };
    }

    public async Task AddEmployeeAsync(AddEmployeeRequest request)
