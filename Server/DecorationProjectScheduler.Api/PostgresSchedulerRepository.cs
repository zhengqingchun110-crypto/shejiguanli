    public async Task ToggleStageAsync(int stageId, bool complete)
    {
        var projectId = await ScalarAsync<int>("SELECT project_id FROM project_stages WHERE id = @stageId;", ("stageId", stageId));
        await ExecuteAsync("""
            UPDATE project_stages
            SET completed_date = @completedDate,
                status = @status
            WHERE id = @stageId;
            """,
            ("stageId", stageId),
            ("completedDate", complete ? DateTime.Today : DBNull.Value),
            ("status", complete ? "已完成" : "待执行"));
        await TouchProjectAsync(projectId);
    }

    private async Task<int> GetTaskProjectIdAsync(int taskId) =>
        await ScalarAsync<int>("SELECT project_id FROM tasks WHERE id = @taskId;", ("taskId", taskId));

    private async Task TouchProjectAsync(int projectId) =>
        await ExecuteAsync("UPDATE projects SET updated_at = @updatedAt WHERE id = @projectId;", ("projectId", projectId), ("updatedAt", DateTime.Now));

    private static async Task TouchProjectAsync(NpgsqlConnection connection, NpgsqlTransaction transaction, int projectId) =>
        await ExecuteAsync(connection, "UPDATE projects SET updated_at = @updatedAt WHERE id = @projectId;", transaction, ("projectId", projectId), ("updatedAt", DateTime.Now));

    private async Task<List<Employee>> ReadEmployeesAsync(NpgsqlConnection connection)
    {
        await using var command = new NpgsqlCommand("SELECT id, name, role, department FROM employees ORDER BY id;", connection);
        await using var reader = await command.ExecuteReaderAsync();
        var list = new List<Employee>();
        while (await reader.ReadAsync())
        {
            list.Add(new Employee { Id = reader.GetInt32(0), Name = reader.GetString(1), Role = reader.GetString(2), Department = reader.GetString(3) });
        }

        return list;
    }

    private async Task<List<Project>> ReadProjectsAsync(NpgsqlConnection connection)
    {
