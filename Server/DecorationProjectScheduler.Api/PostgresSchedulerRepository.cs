    public async Task DeleteProjectFollowUpAsync(int followUpId)
    {
        var projectId = await ScalarAsync<int?>("SELECT project_id FROM project_follow_ups WHERE id = @followUpId;", ("followUpId", followUpId));
        if (projectId is null)
        {
            return;
        }

        await ExecuteAsync("DELETE FROM project_follow_ups WHERE id = @followUpId;", ("followUpId", followUpId));
        await TouchProjectAsync(projectId.Value);
    }

